package com.epl.gateway.configurations;

import com.epl.gateway.graphql.MobileGraphQlSchema;
import com.epl.gateway.models.responses.ApiError;
import com.epl.gateway.rpc.CallMetadata;
import com.epl.gateway.rpc.GrpcHttpStatus;
import com.google.protobuf.InvalidProtocolBufferException;
import com.epl.gateway.graphql.BoundedPersistedQueryCache;
import graphql.GraphqlErrorBuilder;
import graphql.analysis.FieldComplexityCalculator;
import graphql.analysis.MaxQueryComplexityInstrumentation;
import graphql.analysis.MaxQueryDepthInstrumentation;
import graphql.execution.AbortExecutionException;
import graphql.execution.instrumentation.Instrumentation;
import graphql.execution.preparsed.persisted.ApolloPersistedQuerySupport;
import graphql.schema.idl.SchemaPrinter;
import io.grpc.Status;
import io.grpc.StatusRuntimeException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.autoconfigure.graphql.GraphQlSourceBuilderCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.graphql.execution.DataFetcherExceptionResolver;
import org.springframework.graphql.execution.ErrorType;
import org.springframework.graphql.server.WebGraphQlInterceptor;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.oauth2.server.resource.authentication.JwtAuthenticationToken;
import org.springframework.web.context.request.RequestContextHolder;
import org.springframework.web.context.request.ServletRequestAttributes;

import java.nio.charset.StandardCharsets;
import java.util.Map;

/**
 * Mobile API: GraphQL at {@code /api/m/graphql} (GraphiQL {@code /api/m/graphiql}, SDL {@code /api/m/graphql/schema}),
 * schema generated by {@link MobileGraphQlSchema}.
 * <ul>
 *     <li>Automatic Persisted Queries (Apollo): the client sends the SHA-256 of a known query instead of its text;
 *     parsing and validation are cached with it</li>
 *     <li>limits: RPC fields per request ({@code max-rpc-calls}, aliases included) and query depth</li>
 * </ul>
 */
@Configuration
public class GraphQlConfiguration {

    private static final Logger logger = LoggerFactory.getLogger(GraphQlConfiguration.class);
    private static final String REQUEST_ID = GraphQlConfiguration.class.getName() + ".requestId";

    /** The schema is built in code; its SDL is passed as the schema resource Spring GraphQL requires. */
    @Bean
    public GraphQlSourceBuilderCustomizer mobileSchema(MobileGraphQlSchema mobileSchema, GatewayProperties properties) {
        var sdl = new SchemaPrinter().print(mobileSchema.schema());
        var persistedQueries = new ApolloPersistedQuerySupport(
                new BoundedPersistedQueryCache(properties.graphql().persistedQueryCacheSize()));
        return builder -> builder
                .schemaResources(new ByteArrayResource(sdl.getBytes(StandardCharsets.UTF_8), "mobile schema"))
                .schemaFactory((registry, wiring) -> mobileSchema.schema())
                .configureGraphQl(graphQl -> graphQl.preparsedDocumentProvider(persistedQueries));
    }

    /** Each RPC field is one backend call: aliases ({@code a: getProduct … b: getProduct}) must not multiply them unbounded. */
    @Bean
    public Instrumentation maxRpcCalls(MobileGraphQlSchema mobileSchema, GatewayProperties properties) {
        var max = properties.graphql().maxRpcCalls();
        FieldComplexityCalculator rpcCalls = (env, childComplexity) ->
                mobileSchema.isRpcField(env.getParentType().getName(), env.getFieldDefinition().getName()) ? 1 : childComplexity;
        return new MaxQueryComplexityInstrumentation(max, rpcCalls) {
            @Override
            protected AbortExecutionException mkAbortException(int calls, int maxCalls) {
                return new AbortExecutionException("Too many RPC calls in one request: " + calls + " > " + maxCalls);
            }
        };
    }

    @Bean
    public Instrumentation maxDepth(GatewayProperties properties) {
        return new MaxQueryDepthInstrumentation(properties.graphql().maxDepth());
    }

    /** Runs on the request thread: forwarded headers, request id and authentication into the GraphQL context. */
    @Bean
    public WebGraphQlInterceptor callMetadata() {
        return (request, chain) -> {
            var servletRequest = ((ServletRequestAttributes) RequestContextHolder.currentRequestAttributes()).getRequest();
            var context = Map.<Object, Object>of(
                    MobileGraphQlSchema.METADATA, CallMetadata.from(servletRequest),
                    MobileGraphQlSchema.AUTHENTICATED, SecurityContextHolder.getContext().getAuthentication() instanceof JwtAuthenticationToken,
                    REQUEST_ID, RequestIdFilter.requestId(servletRequest));
            request.configureExecutionInput((input, builder) -> builder.graphQLContext(context).build());
            return chain.next(request);
        };
    }

    /** Backend gRPC errors -> GraphQL errors with the same code / message as the REST {@link ApiError}. */
    @Bean
    public DataFetcherExceptionResolver grpcErrors() {
        return DataFetcherExceptionResolver.forSingleError((exception, env) -> {
            Status status;
            if (exception instanceof StatusRuntimeException e) {
                status = e.getStatus();
            } else if (exception instanceof InvalidProtocolBufferException e) {
                status = Status.INVALID_ARGUMENT.withDescription("Invalid input: " + e.getMessage());
            } else {
                return null;
            }
            var httpStatus = GrpcHttpStatus.of(status.getCode());
            // UNIMPLEMENTED is expected while RPCs are still being implemented
            if (httpStatus >= 500 && status.getCode() != Status.Code.UNIMPLEMENTED) {
                logger.warn("GraphQL {} -> {}", env.getExecutionStepInfo().getPath(), status, exception);
            }
            var error = ApiError.of(status, env.getGraphQlContext().getOrDefault(REQUEST_ID, ""));
            return GraphqlErrorBuilder.newError(env)
                    .errorType(errorType(httpStatus))
                    .message(error.message())
                    .extensions(Map.of("code", error.code(), "requestId", error.requestId()))
                    .build();
        });
    }

    private static ErrorType errorType(int httpStatus) {
        return switch (httpStatus) {
            case 401 -> ErrorType.UNAUTHORIZED;
            case 403 -> ErrorType.FORBIDDEN;
            case 404 -> ErrorType.NOT_FOUND;
            default -> httpStatus >= 500 ? ErrorType.INTERNAL_ERROR : ErrorType.BAD_REQUEST;
        };
    }
}
